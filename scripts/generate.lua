-- Generate lua/eaw/generated.lua from EastAsianWidth.txt.
--
-- Usage:
--   nvim --clean --headless -l scripts/generate.lua [path/to/EastAsianWidth.txt]
--
-- If the path is omitted, the latest file is downloaded from unicode.org with curl.

local URL = "https://www.unicode.org/Public/UCD/latest/ucd/EastAsianWidth.txt"

local script_dir = vim.fs.dirname(vim.fs.normalize(debug.getinfo(1, "S").source:sub(2)))
local output = vim.fs.normalize(vim.fs.joinpath(script_dir, "..", "lua", "eaw", "generated.lua"))

---@return string
local function read_source()
  local path = _G.arg[1]
  if path then
    local f = assert(io.open(path, "rb"))
    local body = f:read "*a"
    f:close()
    return body
  end
  local result = vim.system({ "curl", "-sSfL", URL }, { text = true }):wait()
  if result.code ~= 0 then
    error(("curl failed (%d): %s"):format(result.code, result.stderr))
  end
  return result.stdout
end

local body = read_source()

-- The first lines look like:
--   # EastAsianWidth-18.0.0.txt
--   # Date: 2026-06-29, 15:25:05 GMT
local version = body:match "^#%s*EastAsianWidth%-([%d%.]+)%.txt"
local date = body:match "\n#%s*Date:%s*([^\r\n]+)"
if not version then
  error "cannot find the version in the header"
end

local entries = {}
for line in body:gmatch "[^\r\n]+" do
  -- Since Unicode 15.1 the fields are padded with spaces, e.g.
  --   0020           ; Na # Zs         SPACE
  --   0021..0023     ; Na # Po     [3] EXCLAMATION MARK..NUMBER SIGN
  -- Older files have no padding ("0021..0023;Na # Po ..."), which also matches.
  -- The category can be "L&" for ranges mixing Lu, Ll and Lt.
  local codepoints, sign, category, rest = line:match "^([%x%.]+)%s*;%s*(%a%a?)%s*#%s*(%S%S)%s+(.*)$"
  if not codepoints and line:match "^%x" then
    error("cannot parse the line: " .. line)
  end
  if codepoints then
    local s, e = codepoints:match "^(%x+)%.%.(%x+)$"
    s = s or codepoints
    e = e or codepoints
    local count, comment = rest:match "^%[(%d+)%]%s+(.*)$"
    table.insert(entries, {
      tonumber(s, 16),
      tonumber(e, 16),
      sign,
      category,
      tonumber(count) or 1,
      comment or rest,
    })
  end
end

if #entries == 0 then
  error "no entries found; the file format may have changed"
end
table.sort(entries, function(a, b)
  return a[1] < b[1]
end)
for i = 2, #entries do
  if entries[i][1] <= entries[i - 1][2] then
    error(("overlapping ranges: U+%04X and U+%04X"):format(entries[i - 1][1], entries[i][1]))
  end
end

local lines = {
  "-- This file is generated by scripts/generate.lua. DO NOT EDIT.",
  ("-- Source: EastAsianWidth-%s.txt (Date: %s)"):format(version, date or "unknown"),
  "return {",
  ("  version = %q,"):format(version),
  "  entries = {",
}
for _, entry in ipairs(entries) do
  table.insert(
    lines,
    ("    { 0x%04X, 0x%04X, %q, %q, %d, %q },"):format(entry[1], entry[2], entry[3], entry[4], entry[5], entry[6])
  )
end
table.insert(lines, "  },")
table.insert(lines, "}")

local f = assert(io.open(output, "wb"))
f:write(table.concat(lines, "\n") .. "\n")
f:close()
print(("generated %d entries from EastAsianWidth-%s.txt"):format(#entries, version))
